// Regenerates src/core/turnSoundData.ts from assets/turn.wav.
// Run it after replacing the WAV:  node scripts/embed-sound.mjs
//
// assets/turn.wav is the turn sound: 16-bit PCM, mono, 48 kHz, about 144 ms.
// WAV is used on purpose: it decodes instantly in every browser and has no encoder
// delay, so a hit lands exactly when a turn finishes, even for very fast turns.
import { readFileSync, writeFileSync } from 'node:fs';

const wav = readFileSync(new URL('../assets/turn.wav', import.meta.url));
if (wav.toString('ascii', 0, 4) !== 'RIFF' || wav.toString('ascii', 8, 12) !== 'WAVE') {
  throw new Error('assets/turn.wav is not a WAV file.');
}

const out = `// Generated by scripts/embed-sound.mjs from assets/turn.wav. Do not edit by hand.
export const TURN_SOUND_WAV_BASE64 =
  '${wav.toString('base64')}';
`;
writeFileSync(new URL('../src/core/turnSoundData.ts', import.meta.url), out);
console.log(`Embedded ${wav.length} bytes of WAV (${out.length} characters of TypeScript).`);
